const orchard = codeDir + "orchard-pipeline"

func TestNewPlan_Names(t *testing.T) {
	t.Run("a session takes its tmux name up to the first ' · ', trimmed", func(t *testing.T) {
		for tmuxName, want := range map[string]string{
			"orchard-pipeline-Hq7wNe · api review": "orchard-pipeline-Hq7wNe",
			"lantern":                              "lantern",
			"tidepool · flaky test · round two":    "tidepool",
			"no·spaces·around":                     "no·spaces·around",
			"trail  · two spaces before":           "trail",
			"  padded · leading spaces":            "padded",
		} {
			plan := planSessions(t, session(tmuxName, pane(0, orchard)))
			if got := plan.Sessions[0]; got.Name != want || got.Generated != nil {
				t.Errorf("%q named %q (generated: %v), want %q", tmuxName, got.Name, got.Generated, want)
			}
		}
	})

	t.Run("a name too long for zmx is generated by the minting rule", func(t *testing.T) {
		long := strings.Repeat("x", zmxBackend(t).MaxNameLen()+1)
		got := planSessions(t, session(long+" · topic", pane(0, orchard))).Sessions[0]

		if got.Name != "orchard-pipeline-Gen001" {
			t.Errorf("name = %q, want orchard-pipeline-Gen001", got.Name)
		}
		if !errors.Is(got.Generated, backend.ErrInvalidName) {
			t.Errorf("Generated = %v, want the backend's refusal", got.Generated)
		}
	})

	for _, refused := range []string{"-flag", "star*", "logs", "LOGS", "bad/slash", "tab\there", ""} {
		t.Run("a name zmx refuses, "+`"`+refused+`"`+", is generated", func(t *testing.T) {
			got := planSessions(t, session(refused+" · topic", pane(0, orchard))).Sessions[0]

			if got.Name != "orchard-pipeline-Gen001" || !errors.Is(got.Generated, backend.ErrInvalidName) {
				t.Errorf("named %q (generated: %v), want orchard-pipeline-Gen001 for the backend's refusal", got.Name, got.Generated)
			}
		})
	}

	t.Run("a name an earlier session took is generated", func(t *testing.T) {
		plan := planSessions(t, session("api · user search", pane(0, orchard)), session("api · billing", pane(0, orchard)))

		if got := namesOf(plan); !slices.Equal(got, []string{"api", "orchard-pipeline-Gen001"}) {
			t.Errorf("names = %v, want api then a generated one", got)
		}
		assertTakenBy(t, plan.Sessions[1].Generated, "api")
	})

	for what, taken := range map[string]string{
		"a live session or an existing entry holds": "lantern",
		"a name folding to it holds":                "LANTERN",
	} {
		t.Run("a name "+what+" is generated", func(t *testing.T) {
			dir := legacyDir(t, []v1Session{session("lantern", pane(0, orchard))}, nil)
			got := planOf(t, dir, nil, naming(t, "other", taken)).Sessions[0]

			if got.Name != "orchard-pipeline-Gen001" {
				t.Errorf("name = %q, want a generated one", got.Name)
			}
			assertTakenBy(t, got.Generated, taken)
		})
	}

	t.Run("a generated name taken already draws another nanoid", func(t *testing.T) {
		dir := legacyDir(t, []v1Session{session("star*", pane(0, orchard))}, nil)
		got := planOf(t, dir, nil, naming(t, "orchard-pipeline-gen001")).Sessions[0]

		if got.Name != "orchard-pipeline-Gen002" {
			t.Errorf("name = %q, want orchard-pipeline-Gen002", got.Name)
		}
	})

	t.Run("a generated name's project is the last part of the pane's dir, as a mint's", func(t *testing.T) {
		long := codeDir + strings.Repeat("p", 120)
		for cwd, want := range map[string]string{
			orchard + "/web/src":       "orchard-pipeline-Gen001",
			"/tmp/scratch":             "scratch-Gen001",
			codeDir + "My Project/doc": "My Project-Gen001",
			codeDir + "_hidden":        "hidden-Gen001",
			"":                         "session-Gen001",
			"/":                        "session-Gen001",
			long:                       strings.Repeat("p", zmxBackend(t).MaxNameLen()-len("-Gen001")) + "-Gen001",
		} {
			if got := planSessions(t, session("star*", pane(0, cwd))).Sessions[0].Name; got != want {
				t.Errorf("cwd %q gave %q, want %q", cwd, got, want)
			}
		}
	})

	t.Run("no free name to generate fails the plan", func(t *testing.T) {
		dir := legacyDir(t, []v1Session{session("star*", pane(0, orchard))}, nil)
		n := naming(t, "orchard-pipeline-Gen001")
		n.Mint = func() (string, error) { return "Gen001", nil }

		if _, err := migrate.NewPlan(readLegacy(t, dir), nil, n); err == nil {
			t.Error("NewPlan succeeded with every generated name taken")
		}
	})

	t.Run("a mint that fails fails the plan", func(t *testing.T) {
		dir := legacyDir(t, []v1Session{session("star*", pane(0, orchard))}, nil)
		n := naming(t)
		entropy := errors.New("no entropy")
		n.Mint = func() (string, error) { return "", entropy }

		if _, err := migrate.NewPlan(readLegacy(t, dir), nil, n); !errors.Is(err, entropy) {
			t.Errorf("NewPlan = %v, want the mint's failure", err)
		}
	})
}

func assertTakenBy(t *testing.T, generated error, holder string) {
	t.Helper()
	if !errors.Is(generated, migrate.ErrNameTaken) || !strings.Contains(generated.Error(), `"`+holder+`"`) {
		t.Errorf("Generated = %v, want ErrNameTaken naming %q", generated, holder)
	}
}

